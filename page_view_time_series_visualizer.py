from statsmodels.tsa.arima.model import ARIMA
import pandas as pd
import matplotlib.pyplot as plt

def draw_forecast_and_save(df, steps=180):
    # Fit ARIMA; adjust order if needed after experimentation
    model = ARIMA(df['value'], order=(5,1,2))
    model_fit = model.fit()

    # Get forecast with confidence intervals
    fc = model_fit.get_forecast(steps=steps)
    fc_df = fc.summary_frame(alpha=0.05)  # columns: mean, mean_se, mean_ci_lower, mean_ci_upper

    # fc_df index will be the next steps' datetimes if the index is a DatetimeIndex
    # Plot historical + forecast + CI
    fig, ax = plt.subplots(figsize=(12,5))
    ax.plot(df.index, df['value'], label='Historical')
    ax.plot(fc_df.index, fc_df['mean'], label='Forecast', color='green')
    ax.fill_between(fc_df.index, fc_df['mean_ci_lower'], fc_df['mean_ci_upper'],
                    color='k', alpha=0.15, label='95% CI')
    ax.set_title(f'{steps}-day Forecast using ARIMA')
    ax.set_xlabel('Date')
    ax.set_ylabel('Page Views')
    ax.legend()
    plt.show()
    fig.savefig("forecast_with_ci.png")

    # Print top rows and save numeric values
    print("Forecast (first 10 rows):")
    display(fc_df.head(10))   # in Colab this will show a nice table

    # Save to csv
    fc_df.to_csv("forecast_values.csv")
    print("Saved forecast values to forecast_values.csv")

    return fc_df

# call it (after df is defined)
forecast_table = draw_forecast_and_save(df, steps=180)